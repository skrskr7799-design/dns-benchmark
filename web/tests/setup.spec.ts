import {test,expect} from '@playwright/test'
test('fresh instance creates first owner, prevents takeover and supports mobile login',async({page,request,baseURL})=>{
 const origin=baseURL!
 await page.setViewportSize({width:320,height:800})
 await page.goto('/')
 await expect(page.getByRole('heading',{name:'Создание владельца'})).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
 const data={username:'admin',password:'fixture-setup-password-2026'}
 const denied=await request.post('/api/auth/setup',{data,headers:{Origin:'https://external.example','X-NDC-Request':'1'}})
 expect(denied.status()).toBe(403)
 const forwarded=await request.post('/api/auth/setup',{data,headers:{Origin:origin,'X-NDC-Request':'1','X-Forwarded-For':'8.8.8.8'}})
 expect(forwarded.status()).toBe(403)
 const noHeader=await request.post('/api/auth/setup',{data,headers:{Origin:origin}})
 expect(noHeader.status()).toBe(403)
 await page.getByLabel('Имя пользователя').fill(data.username)
 await page.getByLabel('Пароль',{exact:true}).fill('short')
 await page.getByRole('button',{name:'Создать владельца'}).click()
 await expect(page.getByRole('alert')).toHaveText('Введите пароль длиной от 16 до 256 символов.')
 await page.getByLabel('Пароль',{exact:true}).fill(data.password)
 await page.getByLabel('Повторите пароль').fill('mismatch')
 await page.getByRole('button',{name:'Создать владельца'}).click()
 await expect(page.getByRole('alert')).toHaveText('Пароли должны совпадать.')
 await page.getByLabel('Повторите пароль').fill(data.password)
 await page.getByRole('button',{name:'Создать владельца'}).click()
 await expect(page.getByRole('heading',{name:'Network overview'})).toBeVisible()
 const again=await request.post('/api/auth/setup',{data:{...data,username:'attacker'},headers:{Origin:origin,'X-NDC-Request':'1'}})
 expect(again.status()).toBe(409)
 await page.getByRole('button',{name:'Открыть меню'}).click()
 await page.getByRole('button',{name:'Выйти'}).click()
 await expect(page.getByRole('heading',{name:'Вход в систему'})).toBeVisible()
 await page.getByLabel('Имя пользователя').fill(data.username)
 await page.getByLabel('Пароль',{exact:true}).fill(data.password)
 await page.getByRole('button',{name:'Войти',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Network overview'})).toBeVisible()
})
